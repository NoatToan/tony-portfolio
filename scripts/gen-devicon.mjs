#!/usr/bin/env node
/**
 * Copies official devicon artwork (MIT) for brands that simple-icons no longer ships
 * into src/_modules/config/techIconsDevicon.ts as path data, so it renders inline
 * with currentColor. Run after bumping devicon: `node scripts/gen-devicon.mjs`.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';

const root = path.resolve(import.meta.dirname, '..');
const ICONS = {
  aws: 'amazonwebservices/amazonwebservices-plain.svg',
  slack: 'slack/slack-plain.svg',
  azuredevops: 'azuredevops/azuredevops-plain.svg',
};

const out = {};
for (const [key, file] of Object.entries(ICONS)) {
  const svg = readFileSync(path.join(root, 'node_modules/devicon/icons', file), 'utf8');
  const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
  const d = [...svg.matchAll(/\sd="([^"]+)"/g)].map((m) => m[1]).join(' ');
  out[key] = { viewBox, path: d };
}

const body = `// Generated by scripts/gen-devicon.mjs from devicon (MIT). Do not edit by hand.
export const DEVICON_PATHS = ${JSON.stringify(out, null, 2)} as const;
`;
writeFileSync(path.join(root, 'src/_modules/config/techIconsDevicon.ts'), body);
console.log('wrote techIconsDevicon.ts', Object.keys(out));
